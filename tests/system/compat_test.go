// ── encrypted v1.0.0 ─────────────────────────────────────────────────────────

// TestCompat_Encrypted_V1_0_0 verifies that goalie can export from a committed
// encrypted v1.0.0 fixture. The fixture was generated by tests/compat/generate-data.sh
// with --encrypted; encryption_key.hex and key-check.enc are committed so the
// key-check SHA256 in the golden file is stable across runs.
func TestCompat_Encrypted_V1_0_0(t *testing.T) {
	if testing.Short() {
		t.Skip("skipping compatibility test in short mode")
	}

	repo := setupBareRepo(t)
	gh := gitHome(t)
	goalieHome := t.TempDir()

	// Install the committed encryption key so goalie can decrypt the fixture.
	keyHex, err := os.ReadFile("testdata/compat/encrypted-v1.0.0/test_encryption_key.hex")
	if err != nil {
		t.Fatalf("read encryption_key.hex: %v", err)
	}
	if err := os.WriteFile(
		filepath.Join(goalieHome, "encryption.key"),
		bytes.TrimSpace(keyHex), 0600,
	); err != nil {
		t.Fatal(err)
	}

	setupCompatRepo(t,
		"testdata/compat/encrypted-v1.0.0/data",
		repo, gh, goalieHome,
	)
	suppressDailyCheck(t, goalieHome)

	out := runGoalie(t, goalieHome, gh, "", "export")
	assertMatchesGolden(t, out, "testdata/compat/encrypted-v1.0.0/export.golden.jsonl")
}
